CREATE TABLE stock_alert (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    severity VARCHAR(3) NOT NULL CHECK (severity IN ('LOW', 'OUT')),
    opened_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at TIMESTAMPTZ,
    FOREIGN KEY (branch_id, product_id) REFERENCES inventory(branch_id, product_id) ON DELETE CASCADE,
    CHECK (closed_at IS NULL OR closed_at >= opened_at)
);

CREATE UNIQUE INDEX uq_stock_alert_open ON stock_alert(branch_id, product_id)
    WHERE closed_at IS NULL;

INSERT INTO stock_alert(branch_id, product_id, severity)
SELECT branch_id, product_id, CASE WHEN on_hand = reserved THEN 'OUT' ELSE 'LOW' END
FROM inventory
WHERE on_hand = reserved OR on_hand - reserved <= reorder_point;
