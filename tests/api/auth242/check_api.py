def run():
    if (OUT/'cases.json').exists():
        raise SystemExit('Evidence already exists; select a new QA242_REPORT_DIR')
    error=False
    try:
        main()
    except Exception:
        error=True
        print('QA242 interrupted; raw response/error withheld')
    finally:
        cleanup=[]
        for session in SESSIONS:
            if not isinstance(session,dict) or not session.get('accessToken'): continue
            try:
                st,_=http('POST','/auth/logout',session,{'refreshToken':session['refreshToken']})
                if st not in [204,401]: cleanup.append(st)
            except Exception:
                cleanup.append('unavailable')
        for uid in FIXTURE_USERS:
            try:
                sql(f'UPDATE app_user SET is_active=false WHERE id={uid};')
            except Exception:
                cleanup.append('disposable user disable failed')
        OUT.mkdir(parents=True,exist_ok=True)
        expected=set(re.findall(r'^\|\s*((?:TC-AUTH0[12]-\d+|ID-\d+))\s*\|',
            '\n'.join((ROOT/'docs/testing'/name).read_text(encoding='utf-8-sig') for name in
                ['auth-login-jwt-test-cases.md','rbac-branch-filter-test-cases.md','identity-test-cases.md']),re.M))
        for case in expected-CASES.keys():
            CASES[case]=dict(id=case,result='BLOCKED',reason='Run interrupted before case execution')
        supplemental=[v for k,v in CASES.items() if k.startswith('SUPP-')]
        primary=[v for k,v in CASES.items() if not k.startswith('SUPP-')]
        report=dict(issue=242,timestamp=datetime.now(timezone.utc).isoformat(),sourceCommit=SOURCE,
            project=PROJECT,port=PORT,imageId=docker(['inspect',PROJECT+'-backend-1','--format','{{.Image}}']),
            runtimeInterrupted=error,cleanupWarnings=cleanup,summary=dict(Counter(x['result'] for x in primary)),
            supplemental=supplemental,cases=sorted(primary,key=lambda x:x['id']))
        (OUT/'cases.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
        print(json.dumps({'issue':242,'summary':report['summary'],'runtimeInterrupted':error,'cleanupWarnings':cleanup}))
    return 2 if error else (1 if any(x['result']=='FAIL' for x in CASES.values())
        else 2 if any(x['result']=='BLOCKED' for x in CASES.values()) else 0)


if __name__=='__main__':
    raise SystemExit(run())
